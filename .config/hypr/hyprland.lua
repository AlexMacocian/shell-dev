---- AUTOSTART ----
-------------------

-- See https://wiki.hypr.land/Configuring/Basics/Autostart/
hl.on("hyprland.start", function()
	hl.exec_cmd(terminal)

	-- omni-shell replaces waybar (bar), dunst (notification daemon), the wofi power
	-- menu (Control Center) and the standalone omni-launcher daemon.
	hl.exec_cmd("omni-shell & hyprpaper & firefox")

	-- Cycle wallpapers periodically (5 min default, only if multiple images in theme)
	hl.exec_cmd("~/.config/hypr/scripts/wallpaper-cycler.sh 300")

	-- Launch hyprlock on startup as login screen (works with SDDM autologin)
	hl.exec_cmd("hyprlock")

	-- Start AND auto-unlock gnome-keyring-daemon (intune-portal /
	-- microsoft-identity-broker require a password-protected keyring;
	-- SDDM autologin can't unlock it via PAM).
	-- Password is read from ~/.config/hypr/.keyring-pwd (mode 0600).
	hl.exec_cmd("~/.config/hypr/scripts/unlock-keyring.sh")
end)

