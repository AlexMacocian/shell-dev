-- Custom XDG data dirs for repo-managed desktop entries.
-- The list below is rewritten by linux/init-desktop-entries.sh — keep it on one line.
local repoDataDirs = { "shell-dev-general", "shell-dev-work" }

local home = os.getenv("HOME")
local dataDirs = {}
for _, dir in ipairs(repoDataDirs) do
	dataDirs[#dataDirs + 1] = home .. "/.local/share/" .. dir
end
dataDirs[#dataDirs + 1] = home .. "/.local/share"
dataDirs[#dataDirs + 1] = "/usr/local/share"
dataDirs[#dataDirs + 1] = "/usr/share"

hl.env("XDG_DATA_DIRS", table.concat(dataDirs, ":"))

