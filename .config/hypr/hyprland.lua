-- See https://wiki.hypr.land/Configuring/Basics/Binds/
local mainMod = "SUPER" -- Sets "Windows" key as main modifier

hl.bind(mainMod .. " + Q", hl.dsp.exec_cmd(terminal))
hl.bind(mainMod .. " + C", hl.dsp.window.close())
hl.bind(
	mainMod .. " + M",
	hl.dsp.exec_cmd("command -v hyprshutdown >/dev/null 2>&1 && hyprshutdown || hyprctl dispatch 'hl.dsp.exit()'")
)
hl.bind(mainMod .. " + E", hl.dsp.exec_cmd(fileManager))
hl.bind(mainMod .. " + V", hl.dsp.window.float({ action = "toggle" }))
hl.bind(mainMod .. " + R", hl.dsp.exec_cmd(menu))
hl.bind(mainMod .. " + P", hl.dsp.window.pseudo()) -- dwindle
hl.bind(mainMod .. " + J", hl.dsp.layout("togglesplit")) -- dwindle

-- Control Center — power actions (lock/sleep/log off/restart/shutdown), Wi-Fi,
-- Bluetooth, VPN, DND, power profile, volume and brightness. Replaces the wofi
-- power menu that used to be bound here.
hl.bind(mainMod .. " + X", hl.dsp.exec_cmd(shell .. " control toggle"))
hl.bind(mainMod .. " + ALT + P", hl.dsp.exec_cmd(shell .. " control toggle"))

-- Clipboard history
hl.bind(mainMod .. " + SHIFT + V", hl.dsp.exec_cmd(shell .. " clipboard toggle"))

-- Weather panel
hl.bind(mainMod .. " + W", hl.dsp.exec_cmd(shell .. " weather toggle"))

-- Do Not Disturb
hl.bind(mainMod .. " + SHIFT + D", hl.dsp.exec_cmd(shell .. " control dnd"))

-- Theme picker (was reachable from the wofi power menu)
hl.bind(mainMod .. " + SHIFT + T", hl.dsp.exec_cmd("rainbeau select --themes-dir ~/.config/rainbeau/themes/"))

-- Move focus with mainMod + arrow keys
hl.bind(mainMod .. " + left", hl.dsp.focus({ direction = "left" }))
hl.bind(mainMod .. " + right", hl.dsp.focus({ direction = "right" }))
hl.bind(mainMod .. " + up", hl.dsp.focus({ direction = "up" }))
hl.bind(mainMod .. " + down", hl.dsp.focus({ direction = "down" }))

-- Switch workspaces with mainMod + [0-9]
-- Move active window to a workspace with mainMod + SHIFT + [0-9]
for i = 1, 10 do
	local key = i % 10 -- 10 maps to key 0
	hl.bind(mainMod .. " + " .. key, hl.dsp.focus({ workspace = i }))
	hl.bind(mainMod .. " + SHIFT + " .. key, hl.dsp.window.move({ workspace = i }))
end

-- Move active window to another monitor
hl.bind(mainMod .. " + SHIFT + left", hl.dsp.window.move({ monitor = "-1" }))
hl.bind(mainMod .. " + SHIFT + right", hl.dsp.window.move({ monitor = "+1" }))

-- Fullscreen toggle
hl.bind(mainMod .. " + F", hl.dsp.window.fullscreen())

-- Take screenshot of region
hl.bind(mainMod .. " + SHIFT + S", hl.dsp.exec_cmd('grim -g "$(slurp)" - | wl-copy'))

-- Toggle screen recording (start/stop, saves to ~/Documents/Recordings)
hl.bind(mainMod .. " + SHIFT + R", hl.dsp.exec_cmd("~/.config/hypr/scripts/screen-record.sh"))

-- Switch to a random wallpaper (image or video)
hl.bind(mainMod .. " + SHIFT + W", hl.dsp.exec_cmd("~/.config/hypr/scripts/wallpaper-switch.sh"))

-- Example special workspace (scratchpad)
hl.bind(mainMod .. " + S", hl.dsp.workspace.toggle_special("magic"))

-- Scroll through existing workspaces with mainMod + scroll
hl.bind(mainMod .. " + mouse_down", hl.dsp.focus({ workspace = "e+1" }))
hl.bind(mainMod .. " + mouse_up", hl.dsp.focus({ workspace = "e-1" }))

-- Move/resize windows with mainMod + LMB/RMB and dragging
hl.bind(mainMod .. " + mouse:272", hl.dsp.window.drag(), { mouse = true })
hl.bind(mainMod .. " + mouse:273", hl.dsp.window.resize(), { mouse = true })

