-- Backdrop blur for the omni-shell surfaces (bar, notification centre, control
-- centre, launcher, toasts). ignore_alpha masks the blur to non-transparent
-- pixels, so the gaps between bar sections and the rounded corners stay sharp —
-- an unmasked blur rule blurs the whole surface bounding box instead.
hl.layer_rule({
	name = "omni-shell-blur",
	match = { namespace = "^(quickshell)$" },

	blur = true,
	ignore_alpha = 0,
})
